//! Bounded, owner-bound project import into an unpublished staging directory.
use crate::api::{ApiError, AppState, AuthUser};
use axum::{
    Json,
    extract::{Path, State},
    http::StatusCode,
};
use base64::{Engine, engine::general_purpose::STANDARD};
use dunlin_workspace::project_copy::{self, BUNDLE, Manifest};
use serde::Deserialize;
use serde_json::{Value, json};
use std::{
    collections::HashMap,
    fs::{self, OpenOptions},
    io::{Seek, SeekFrom, Write},
    path::PathBuf,
    time::{Duration, Instant},
};

pub struct Pending {
    owner: String,
    created: Instant,
    stage: PathBuf,
    manifest: Manifest,
    offsets: HashMap<String, u64>,
    published: bool,
}
impl Drop for Pending {
    fn drop(&mut self) {
        // This path is generated by the server, never supplied by the client.
        if !self.published {
            let _ = fs::remove_dir_all(&self.stage);
        }
    }
}
fn valid<'a>(
    pending: &'a mut HashMap<String, Pending>,
    id: &str,
    owner: &str,
) -> Result<&'a mut Pending, ApiError> {
    pending
        .get_mut(id)
        .filter(|p| p.owner == owner && p.created.elapsed() < Duration::from_secs(1800))
        .ok_or_else(ApiError::not_found)
}
pub async fn begin(
    auth: AuthUser,
    State(state): State<AppState>,
    Json(manifest): Json<Manifest>,
) -> Result<Json<Value>, ApiError> {
    super::admin(&auth)?;
    project_copy::validate(&manifest).map_err(ApiError::bad_request)?;
    let root = super::root(&state.config).join("projects");
    super::private_dir(&root).map_err(ApiError::internal)?;
    if root.join(&manifest.name).symlink_metadata().is_ok() {
        return Err(ApiError::conflict(
            "A project with this name already exists; choose another name",
        ));
    }
    let mut management = state
        .management
        .lock()
        .map_err(|_| ApiError::internal("Management lock poisoned"))?;
    management
        .copies
        .retain(|_, p| p.created.elapsed() < Duration::from_secs(1800));
    if management.copies.len() >= 2 {
        return Err(ApiError::conflict(
            "Two project transfers are already active",
        ));
    }
    let id = uuid::Uuid::now_v7().to_string();
    let stage = root.join(format!(".transfer-{id}"));
    fs::create_dir(&stage).map_err(|e| ApiError::internal(e.to_string()))?;
    super::private_dir(&stage).map_err(ApiError::internal)?;
    management.copies.insert(
        id.clone(),
        Pending {
            owner: auth.user.id,
            created: Instant::now(),
            stage,
            manifest,
            offsets: HashMap::new(),
            published: false,
        },
    );
    Ok(Json(json!({"id":id})))
}

#[derive(Deserialize)]
#[serde(deny_unknown_fields)]
pub struct Chunk {
    path: String,
    offset: u64,
    contents: String,
}
pub async fn chunk(
    auth: AuthUser,
    State(state): State<AppState>,
    Path(id): Path<String>,
    Json(chunk): Json<Chunk>,
) -> Result<StatusCode, ApiError> {
    super::admin(&auth)?;
    if chunk.contents.len() > project_copy::CHUNK * 4 / 3 + 4 {
        return Err(ApiError::bad_request("Transfer chunk exceeds 1 MiB"));
    }
    let bytes = STANDARD
        .decode(&chunk.contents)
        .map_err(|_| ApiError::bad_request("Invalid transfer encoding"))?;
    if bytes.len() > project_copy::CHUNK {
        return Err(ApiError::bad_request("Transfer chunk exceeds 1 MiB"));
    }
    let mut management = state
        .management
        .lock()
        .map_err(|_| ApiError::internal("Management lock poisoned"))?;
    let pending = valid(&mut management.copies, &id, &auth.user.id)?;
    let entry = pending
        .manifest
        .files
        .iter()
        .find(|f| f.path == chunk.path)
        .ok_or_else(|| ApiError::bad_request("File is not in the transfer manifest"))?;
    let offset = *pending.offsets.get(&chunk.path).unwrap_or(&0);
    if offset != chunk.offset
        || offset
            .checked_add(bytes.len() as u64)
            .is_none_or(|n| n > entry.size)
    {
        return Err(ApiError::conflict(
            "Transfer offset or file size mismatch; do not retry blindly",
        ));
    }
    let path = pending.stage.join(&chunk.path);
    if let Some(parent) = path.parent() {
        fs::create_dir_all(parent).map_err(|e| ApiError::internal(e.to_string()))?;
    }
    let mut options = OpenOptions::new();
    options.write(true);
    if !pending.offsets.contains_key(&chunk.path) {
        options.create_new(true);
    }
    #[cfg(unix)]
    {
        use std::os::unix::fs::OpenOptionsExt;
        options.custom_flags(libc::O_NOFOLLOW).mode(0o600);
    }
    let mut file = options
        .open(&path)
        .map_err(|e| ApiError::conflict(format!("Could not write transfer file: {e}")))?;
    file.seek(SeekFrom::Start(offset))
        .and_then(|_| file.write_all(&bytes))
        .map_err(|e| ApiError::internal(e.to_string()))?;
    pending
        .offsets
        .insert(chunk.path, offset + bytes.len() as u64);
    pending.created = Instant::now();
    Ok(StatusCode::NO_CONTENT)
}

pub async fn finish(
    auth: AuthUser,
    State(state): State<AppState>,
    Path(id): Path<String>,
) -> Result<Json<Value>, ApiError> {
    super::admin(&auth)?;
    let pending = {
        let mut management = state
            .management
            .lock()
            .map_err(|_| ApiError::internal("Management lock poisoned"))?;
        valid(&mut management.copies, &id, &auth.user.id)?;
        management
            .copies
            .remove(&id)
            .ok_or_else(ApiError::not_found)?
    };
    let owner = auth.user.id;
    let project = super::super::api::run_blocking(move || {
        let mut pending = pending;
        for entry in &pending.manifest.files {
            if pending.offsets.get(&entry.path) != Some(&entry.size) {
                return Err("Incomplete transfer".into());
            }
            let path = pending.stage.join(&entry.path);
            if fs::metadata(&path).map_err(|e| e.to_string())?.len() != entry.size
                || project_copy::digest(&path)? != entry.sha256
            {
                return Err(
                    "Transfer checksum mismatch; the local project may have changed".into(),
                );
            }
            #[cfg(unix)]
            {
                use std::os::unix::fs::PermissionsExt;
                fs::set_permissions(
                    &path,
                    fs::Permissions::from_mode(if entry.executable { 0o700 } else { 0o600 }),
                )
                .map_err(|e| e.to_string())?;
            }
        }
        if pending.manifest.history {
            // shortcut: history import assumes SHA-1; carry object-format metadata before supporting SHA-256 repositories.
            project_copy::git(&pending.stage, &["init", "-q"])?;
            project_copy::git(
                &pending.stage,
                &[
                    "fetch",
                    "--update-head-ok",
                    "--no-write-fetch-head",
                    BUNDLE,
                    "refs/heads/*:refs/heads/*",
                    "refs/tags/*:refs/tags/*",
                ],
            )?;
            let branch = pending
                .manifest
                .branch
                .as_deref()
                .ok_or("Missing Git branch")?;
            project_copy::git(
                &pending.stage,
                &["symbolic-ref", "HEAD", &format!("refs/heads/{branch}")],
            )?;
            // shortcut: staging becomes unstaged; export a portable index when staged-state fidelity is required.
            project_copy::git(&pending.stage, &["reset", "--mixed", "HEAD"])?;
            fs::remove_file(pending.stage.join(BUNDLE)).map_err(|e| e.to_string())?;
        }
        let destination = pending
            .stage
            .parent()
            .ok_or("Missing project root")?
            .join(&pending.manifest.name);
        dunlin_workspace::transfer::publish_directory(&pending.stage, &destination)?;
        let result = (|| {
            let store = state
                .store
                .lock()
                .map_err(|_| "Store lock poisoned".to_string())?;
            let project = store
                .create_project(
                    &pending.manifest.name,
                    destination.to_str().ok_or("Invalid project destination")?,
                )
                .map_err(|e| e.to_string())?;
            store
                .grant(&project.id, &owner)
                .map_err(|e| e.to_string())?;
            Ok::<_, String>(project)
        })();
        // Keep a completed copy if registration fails; never delete user content.
        pending.published = true;
        result.map_err(|e| {
            format!(
                "Files copied to {} but registration failed: {e}",
                destination.display()
            )
        })
    })
    .await?;
    Ok(Json(json!(project)))
}

pub async fn cancel(
    auth: AuthUser,
    State(state): State<AppState>,
    Path(id): Path<String>,
) -> Result<StatusCode, ApiError> {
    super::admin(&auth)?;
    let mut management = state
        .management
        .lock()
        .map_err(|_| ApiError::internal("Management lock poisoned"))?;
    valid(&mut management.copies, &id, &auth.user.id)?;
    management.copies.remove(&id);
    Ok(StatusCode::NO_CONTENT)
}
